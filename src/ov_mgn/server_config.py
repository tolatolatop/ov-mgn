def get_config_dir(home: Path | None = None) -> Path:
    return (home or Path.home()) / CONFIG_DIR_NAME


def get_server_config_path(home: Path | None = None) -> Path:
    return get_config_dir(home) / SERVER_CONFIG_NAME


def get_server_lock_path(home: Path | None = None) -> Path:
    return get_config_dir(home) / SERVER_LOCK_NAME


def get_release_lock_path(home: Path | None = None) -> Path:
    return get_config_dir(home) / RELEASE_LOCK_NAME


def get_state_path(home: Path | None = None) -> Path:
    return get_config_dir(home) / STATE_NAME


def load_user_server_config(path: Path | None = None) -> UserServerConfig:
    config_path = path or get_server_config_path()
    if not config_path.exists():
        return UserServerConfig()

    with config_path.open("r", encoding="utf-8") as file:
        return UserServerConfig.model_validate(json.load(file))


def save_user_server_config(config: UserServerConfig, path: Path | None = None) -> Path:
    config_path = path or get_server_config_path()
    validated = UserServerConfig.model_validate(config.model_dump(mode="python"))
    return _write_user_json_atomic(validated, config_path)


def save_user_server_config_data(data: dict[str, Any], path: Path | None = None) -> Path:
    UserServerConfig.model_validate(data)
    return _write_user_json_data_atomic(data, path or get_server_config_path())


def update_user_server_config(
    updater: Callable[[UserServerConfig], None],
    path: Path | None = None,
) -> UserServerConfig:
    config = load_user_server_config(path)
    updater(config)
    validated = UserServerConfig.model_validate(config.model_dump(mode="python"))
    save_user_server_config(validated, path)
    return validated


def load_locked_config(path: Path | None = None) -> LockedServerConfig:
    with (path or get_server_lock_path()).open("r", encoding="utf-8") as file:
        return LockedServerConfig.model_validate(json.load(file))


def load_release_lock(path: Path | None = None) -> ReleaseLock:
    release_path = path or get_release_lock_path()
