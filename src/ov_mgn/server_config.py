def load_user_server_config(path: Path | None = None) -> UserServerConfig:
    config_path = path or get_server_config_path()
    if not config_path.exists():
        return UserServerConfig()

    with config_path.open("r", encoding="utf-8") as file:
        return UserServerConfig.model_validate(json.load(file))


def save_user_server_config(config: UserServerConfig, path: Path | None = None) -> Path:
    config_path = path or get_server_config_path()
    validated = UserServerConfig.model_validate(config.model_dump(mode="python"))
    return _write_user_json_atomic(validated, config_path)


def save_user_server_config_data(data: dict[str, Any], path: Path | None = None) -> Path:
    UserServerConfig.model_validate(data)
