def _write_json_read_only(model: BaseModel, path: Path) -> Path:
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    if path.exists():
        path.chmod(0o600)
    with path.open("w", encoding="utf-8") as file:
        json.dump(_json_ready(model), file, ensure_ascii=False, indent=2)
        file.write("\n")
    path.chmod(0o444)
    return path


def _write_user_json_atomic(model: BaseModel, path: Path) -> Path:
    return _write_user_json_data_atomic(_json_ready(model), path)


def _write_user_json_data_atomic(data: dict[str, Any], path: Path) -> Path:
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=path.parent,
        text=True,
    )
    temp_path = Path(temp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as file:
            json.dump(data, file, ensure_ascii=False, indent=2, sort_keys=True)
            file.write("\n")
            file.flush()
            os.fsync(file.fileno())
        temp_path.chmod(0o600)
        os.replace(temp_path, path)
        path.chmod(0o600)
    except Exception:
        try:
            temp_path.unlink()
        except FileNotFoundError:
            pass
        raise
    return path


def _json_ready(model: BaseModel) -> dict[str, Any]:
    return model.model_dump(mode="json")


def is_read_only(path: Path) -> bool:
    return path.exists() and path.stat().st_mode & 0o222 == 0
