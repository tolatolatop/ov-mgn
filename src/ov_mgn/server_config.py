from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

CONFIG_DIR_NAME = ".ov_mgn"
SERVER_CONFIG_NAME = "server.json"
SERVER_LOCK_NAME = "server.json.lock"
RELEASE_LOCK_NAME = "release.json.lock"
STATE_NAME = "state.json"
DEFAULT_CONFIG_TEMPLATE = """# Generated by ov-mgn.
profile = "${profile}"
service = "${service}"
release_id = "${release_id}"
"""
SERVICE_NAME_PATTERN = re.compile(r"^[A-Za-z][A-Za-z0-9_-]*$")
ENV_KEY_PATTERN = re.compile(r"^[A-Z_][A-Z0-9_]*$")


class SourceSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    type: Literal["git", "local"]
    repo: str | None = Field(default=None)
    ref: str | None = Field(default=None)
    path: Path | None = Field(default=None)

    @model_validator(mode="after")
    def validate_source(self) -> "SourceSpec":
        if self.type == "git" and not (self.repo and self.repo.strip()):
            raise ValueError("git source requires repo")
        if self.type == "local" and not self.path:
            raise ValueError("local source requires path")
        if self.type == "local" and self.path:
            source_path = self.path.expanduser()
            if not source_path.exists() or not source_path.is_dir():
                raise ValueError("local source path must exist and be a directory")
        return self


class OpenVikingSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    vars: dict[str, str] = Field(default_factory=dict)
    env: dict[str, str] = Field(default_factory=dict)
    template_path: Path | None = Field(default=None)

    @field_validator("vars")
    @classmethod
    def validate_vars(cls, value: dict[str, str]) -> dict[str, str]:
        for key in value:
            if not isinstance(key, str) or not key:
                raise ValueError("vars keys must be non-empty strings")
        return value

    @field_validator("env")
    @classmethod
    def validate_env(cls, value: dict[str, str]) -> dict[str, str]:
        for key in value:
            if not isinstance(key, str) or not ENV_KEY_PATTERN.fullmatch(key):
                raise ValueError("env keys must match [A-Z_][A-Z0-9_]*")
        return value

    @field_validator("template_path")
    @classmethod
    def validate_template_path(cls, value: Path | None) -> Path | None:
        if value is None:
            return value
        template_path = value.expanduser()
        if not template_path.exists() or not template_path.is_file():
            raise ValueError("template_path must exist and be a file")
        return value


class ServerDefaults(BaseModel):
    model_config = ConfigDict(extra="forbid")

    port_range: tuple[int, int] = Field(default=(30000, 39999))
    image: str = Field(default="openviking/openviking:latest")
    data_root: Path = Field(default=Path("~/.ov_mgn/data"))
    secret_env_file: Path | None = Field(default=Path("~/.ov_mgn/secrets.env"))

    @field_validator("port_range")
    @classmethod
    def validate_port_range(cls, value: tuple[int, int]) -> tuple[int, int]:
        start, end = value
        if start < 1 or end > 65535 or start > end:
            raise ValueError("port_range must be within 1..65535 and start <= end")
        return value


class ServiceSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    enabled: bool = Field(default=True)
    stable_host: str = Field(default="127.0.0.1")
    stable_port: int = Field(ge=1, le=65535)
    image: str | None = Field(default=None)
    source: SourceSpec
    openviking: OpenVikingSpec = Field(default_factory=OpenVikingSpec)


class UserServerConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    version: int = Field(default=1)
    defaults: ServerDefaults = Field(default_factory=ServerDefaults)
    services: dict[str, ServiceSpec] = Field(default_factory=dict)

    @model_validator(mode="after")
    def validate_services(self) -> "UserServerConfig":
        stable_ports: dict[int, str] = {}
        range_start, range_end = self.defaults.port_range
        for name, service in self.services.items():
            if not SERVICE_NAME_PATTERN.fullmatch(name):
                raise ValueError(f"invalid service name: {name}")
            if service.stable_port in stable_ports:
                other = stable_ports[service.stable_port]
                raise ValueError(
                    f"stable_port {service.stable_port} is used by both {other} and {name}"
                )
            stable_ports[service.stable_port] = name
            if range_start <= service.stable_port <= range_end:
                raise ValueError(
                    f"port_range {range_start}-{range_end} must not include stable_port "
                    f"{service.stable_port} for {name}"
                )
        return self


