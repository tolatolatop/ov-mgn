def _merged_runtime_env(secret_env_file: Path | None, values: dict[str, str]) -> str:
    lines: list[str] = []
    if secret_env_file:
        secret_path = secret_env_file.expanduser()
        if secret_path.exists():
            lines.extend(
                line
                for line in secret_path.read_text(encoding="utf-8").splitlines()
                if _env_line_key(line) not in OPENVIKING_MANAGED_ENV_KEYS
            )
            lines.append("")
    lines.extend(f"{key}={value}" for key, value in sorted(values.items()))
    return "\n".join(lines).rstrip() + "\n"


def _env_line_key(line: str) -> str | None:
    stripped = line.strip()
    if not stripped or stripped.startswith("#") or "=" not in stripped:
        return None
    return stripped.split("=", 1)[0].strip()


def _write_json_read_only(model: BaseModel, path: Path) -> Path:
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    if path.exists():
        path.chmod(0o600)
    with path.open("w", encoding="utf-8") as file:
        json.dump(_json_ready(model), file, ensure_ascii=False, indent=2)
        file.write("\n")
    path.chmod(0o444)
    return path


def _write_user_json_atomic(model: BaseModel, path: Path) -> Path:
    return _write_user_json_data_atomic(_json_ready(model), path)


def _write_user_json_data_atomic(data: dict[str, Any], path: Path) -> Path:
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=path.parent,
        text=True,
    )
    temp_path = Path(temp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as file:
            json.dump(data, file, ensure_ascii=False, indent=2, sort_keys=True)
            file.write("\n")
            file.flush()
            os.fsync(file.fileno())
        temp_path.chmod(0o600)
        os.replace(temp_path, path)
        path.chmod(0o600)
    except Exception:
        try:
            temp_path.unlink()
        except FileNotFoundError:
            pass
        raise
    return path


def _json_ready(model: BaseModel) -> dict[str, Any]:
    return model.model_dump(mode="json")


def is_read_only(path: Path) -> bool:
    return path.exists() and path.stat().st_mode & 0o222 == 0
