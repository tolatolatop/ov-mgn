class BranchSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    parent_service: str
    declared_at: datetime

    @field_validator("parent_service")
    @classmethod
    def validate_parent_service(cls, value: str) -> str:
        if not SERVICE_NAME_PATTERN.fullmatch(value):
            raise ValueError("branch parent_service must be a valid service name")
        return value


class ServiceSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    enabled: bool = Field(default=True)
    stable_host: str = Field(default="127.0.0.1")
    stable_port: int = Field(default=0, ge=0, le=65535)
    route_path: str | None = Field(default=None)
    image: str | None = Field(default=None)
    source: SourceSpec
    openviking: OpenVikingSpec = Field(default_factory=OpenVikingSpec)
    branch: BranchSpec | None = Field(default=None)

    @field_validator("route_path")
    @classmethod
    def validate_route_path(cls, value: str | None) -> str | None:
        if value is None:
            return value
        if not ROUTE_PATH_PATTERN.fullmatch(value):
            raise ValueError("route_path must start and end with / and contain path-safe chars")
        if "/__candidate/" in value:
            raise ValueError("route_path must not include __candidate")
        if value.startswith("/__ov-mgn/"):
            raise ValueError("route_path must not use reserved /__ov-mgn/ prefix")
        return value


class GatewayDefaults(BaseModel):
    model_config = ConfigDict(extra="forbid")

    enabled: bool = Field(default=True)
    host: str = Field(default="127.0.0.1")
    port: int = Field(default=18080, ge=1, le=65535)
    image: str = Field(default="nginx:stable-alpine")
    network_name: str = Field(default="ov-mgn-gateway")

    @model_validator(mode="after")
    def validate_gateway(self) -> "GatewayDefaults":
        if not self.enabled:
            raise ValueError(
                "only gateway mode is supported; defaults.gateway.enabled must be true"
            )
        return self


class UserServerConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    version: int = Field(default=1)
    defaults: ServerDefaults = Field(default_factory=ServerDefaults)
    services: dict[str, ServiceSpec] = Field(default_factory=dict)

    @model_validator(mode="after")
    def validate_services(self) -> "UserServerConfig":
        route_paths: dict[str, str] = {}
        for name, service in self.services.items():
            if not SERVICE_NAME_PATTERN.fullmatch(name):
                raise ValueError(f"invalid service name: {name}")
            route_path = service.route_path or f"/{name}/"
            if route_path.startswith("/__ov-mgn/"):
                raise ValueError("route_path must not use reserved /__ov-mgn/ prefix")
            if route_path in route_paths:
                other = route_paths[route_path]
                raise ValueError(f"route_path {route_path} is used by both {other} and {name}")
            if service.branch:
                if service.branch.parent_service == name:
                    raise ValueError(f"service {name} cannot branch from itself")
                if service.branch.parent_service not in self.services:
                    raise ValueError(
                        f"branch parent_service {service.branch.parent_service} "
                        f"for {name} is not present in services"
                    )
            route_paths[route_path] = name
        return self


