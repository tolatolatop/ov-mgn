ENV_KEY_PATTERN = re.compile(r"^[A-Z_][A-Z0-9_]*$")
ROUTE_PATH_PATTERN = re.compile(r"^/[A-Za-z0-9_/-]*/$")


class SourceSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    type: Literal["git", "local"]
    repo: str | None = Field(default=None)
    ref: str | None = Field(default=None)
    path: Path | None = Field(default=None)

    @model_validator(mode="after")
    def validate_source(self) -> "SourceSpec":
        if self.type == "git" and not (self.repo and self.repo.strip()):
            raise ValueError("git source requires repo")
        if self.type == "local" and not self.path:
            raise ValueError("local source requires path")
        if self.type == "local" and self.path:
            source_path = self.path.expanduser()
            if not source_path.exists() or not source_path.is_dir():
                raise ValueError("local source path must exist and be a directory")
        return self


class OpenVikingSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    vars: dict[str, str] = Field(default_factory=dict)
    env: dict[str, str] = Field(default_factory=dict)
    template_path: Path | None = Field(default=None)

    @field_validator("vars")
    @classmethod
    def validate_vars(cls, value: dict[str, str]) -> dict[str, str]:
        for key in value:
            if not isinstance(key, str) or not key:
                raise ValueError("vars keys must be non-empty strings")
        return value

    @field_validator("env")
    @classmethod
    def validate_env(cls, value: dict[str, str]) -> dict[str, str]:
        for key in value:
            if not isinstance(key, str) or not ENV_KEY_PATTERN.fullmatch(key):
                raise ValueError("env keys must match [A-Z_][A-Z0-9_]*")
            if key in OPENVIKING_MANAGED_ENV_KEYS:
                raise ValueError(f"{key} is managed by ov-mgn and cannot be set in openviking.env")
        return value


class ServerDefaults(BaseModel):
    model_config = ConfigDict(extra="forbid")

    port_range: tuple[int, int] = Field(default=(30000, 39999))
    image: str = Field(default="ghcr.io/volcengine/openviking:latest")
    backend_port: int = Field(default=1933, ge=1, le=65535)
    data_root: Path = Field(default=Path("~/.ov_mgn/data"))
    secret_env_file: Path | None = Field(default=None)
    openviking: "OpenVikingDefaults" = Field(default_factory=lambda: OpenVikingDefaults())
    gateway: "GatewayDefaults" = Field(default_factory=lambda: GatewayDefaults())

    @field_validator("port_range")
    @classmethod
    def validate_port_range(cls, value: tuple[int, int]) -> tuple[int, int]:
        start, end = value
        if start < 1 or end > 65535 or start > end:
            raise ValueError("port_range must be within 1..65535 and start <= end")
        return value


class OpenVikingDefaults(BaseModel):
    model_config = ConfigDict(extra="forbid")

    model_config_file: Path = Field(default=Path("~/.ov_mgn/model.json"))
    root_api_key: str | None = Field(default=None)

    @field_validator("root_api_key")
    @classmethod
    def validate_root_api_key(cls, value: str | None) -> str | None:
        if value is None:
            return value
        stripped = value.strip()
        if not stripped:
            raise ValueError("root_api_key must be non-empty")
        return stripped


class BranchSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    parent_service: str
    declared_at: datetime

    @field_validator("parent_service")
    @classmethod
    def validate_parent_service(cls, value: str) -> str:
        if not SERVICE_NAME_PATTERN.fullmatch(value):
            raise ValueError("branch parent_service must be a valid service name")
        return value


class ServiceSpec(BaseModel):
    model_config = ConfigDict(extra="forbid")

    enabled: bool = Field(default=True)
    stable_host: str = Field(default="127.0.0.1")
    stable_port: int = Field(default=0, ge=0, le=65535)
    route_path: str | None = Field(default=None)
    image: str | None = Field(default=None)
    source: SourceSpec
    openviking: OpenVikingSpec = Field(default_factory=OpenVikingSpec)
    branch: BranchSpec | None = Field(default=None)

    @field_validator("route_path")
    @classmethod
    def validate_route_path(cls, value: str | None) -> str | None:
        if value is None:
            return value
        if not ROUTE_PATH_PATTERN.fullmatch(value):
            raise ValueError("route_path must start and end with / and contain path-safe chars")
        if "/__candidate/" in value:
            raise ValueError("route_path must not include __candidate")
        if value.startswith("/__ov-mgn/"):
            raise ValueError("route_path must not use reserved /__ov-mgn/ prefix")
        return value


class GatewayDefaults(BaseModel):
    model_config = ConfigDict(extra="forbid")

    enabled: bool = Field(default=True)
    host: str = Field(default="127.0.0.1")
    port: int = Field(default=18080, ge=1, le=65535)
    image: str = Field(default="nginx:stable-alpine")
    network_name: str = Field(default="ov-mgn-gateway")

    @model_validator(mode="after")
    def validate_gateway(self) -> "GatewayDefaults":
        if not self.enabled:
            raise ValueError(
                "only gateway mode is supported; defaults.gateway.enabled must be true"
            )
        return self


class UserServerConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    version: int = Field(default=1)
    defaults: ServerDefaults = Field(default_factory=ServerDefaults)
    services: dict[str, ServiceSpec] = Field(default_factory=dict)

    @model_validator(mode="after")
    def validate_services(self) -> "UserServerConfig":
        route_paths: dict[str, str] = {}
        for name, service in self.services.items():
            if not SERVICE_NAME_PATTERN.fullmatch(name):
                raise ValueError(f"invalid service name: {name}")
            route_path = service.route_path or f"/{name}/"
            if route_path.startswith("/__ov-mgn/"):
                raise ValueError("route_path must not use reserved /__ov-mgn/ prefix")
            if route_path in route_paths:
                other = route_paths[route_path]
                raise ValueError(f"route_path {route_path} is used by both {other} and {name}")
            if service.branch:
                if service.branch.parent_service == name:
                    raise ValueError(f"service {name} cannot branch from itself")
                if service.branch.parent_service not in self.services:
                    raise ValueError(
                        f"branch parent_service {service.branch.parent_service} "
                        f"for {name} is not present in services"
                    )
            route_paths[route_path] = name
        return self


